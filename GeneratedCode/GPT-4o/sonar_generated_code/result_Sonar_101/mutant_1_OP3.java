class ConditionalReachabilityExample {

    public void showBug() {
        boolean a = false;
        if (a) { // BUG: Conditionally executed code should be reachable
            doSomething(); // This code is never executed
        }
        
        boolean b = true;
        if (!a || b) { // BUG: Conditionally executed code should be reachable
            doSomething(); 
        } else {
            doSomethingElse(); // This code is never executed
        }
        
        // Mutation: Insert an unreachable if branch
        boolean randomCondition = getRandomCondition();
        if (randomCondition) { // This if block is unreachable
            doSomethingElse();
        }
    }

    private void doSomething() {
        System.out.println("Doing something!");
    }

    private void doSomethingElse() {
        System.out.println("Doing something else!");
    }

    // Method to simulate a dynamic condition for the unreachable if statement
    private boolean getRandomCondition() {
        return false; // Ensures the condition is false at runtime
    }
    
    public static void main(String[] args) {
        ConditionalReachabilityExample example = new ConditionalReachabilityExample();
        example.showBug();
    }
}