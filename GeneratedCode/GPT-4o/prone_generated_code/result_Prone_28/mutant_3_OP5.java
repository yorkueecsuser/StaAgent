class ConstantOverflowExample {

    // Intent was for the multiplication expression to be evaluated as a long instead of an int.
    static final long NANOS_PER_DAY = 24 * 60 * 60 * 1000 * 1000 * 1000; // BUG: ConstantOverflow

    public long showBug() {
        // Adding an unreachable switch statement
        int nonFinalValue = getNonFinalValue();
        switch (nonFinalValue) {
            case 1:
                System.out.println("This is case 1");
                break;
            case 2:
                System.out.println("This is case 2");
                break;
            default:
                System.out.println("This is the default case");
                break;
        }
        return NANOS_PER_DAY;
    }

    public static void main(String[] args) {
        ConstantOverflowExample example = new ConstantOverflowExample();
        System.out.println("NANOS_PER_DAY with bug: " + example.showBug());
    }

    // This method simulates a runtime-determined value to prevent unreachable code
    private int getNonFinalValue() {
        return 3; // This value is not handled by the switch, making the cases unreachable
    }
}