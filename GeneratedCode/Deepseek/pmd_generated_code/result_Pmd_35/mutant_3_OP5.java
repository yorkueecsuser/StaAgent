import java.lang.System;

class HardcodedSDCard {
    protected void foo() {
        String storageLocation = "/sdcard/mypackage";   // hard-coded, poor approach
        // BUG: DoNotHardCodeSDCard
        storageLocation = System.getenv("SECONDARY_STORAGE") + "/mypackage"; // preferred approach
    }

    public String showBug() {
        foo();
        return "/sdcard/mypackage"; // This is the value that is generated by the buggy code
    }

    // Mutant Added: Unreachable Switch Statement
    public void mutantUnreachableSwitchStatement() {
        int value = 0;
        switch (value) { // This switch statement will always fall-through and never get to the default case, hence it is unreachable
            case 1:
                System.out.println("This is unreachable code");
                break;
            default:
                break;
        }
    }
}