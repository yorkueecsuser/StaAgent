import java.lang.System;

class HardcodedSDCard {
    protected void foo() {
        String storageLocation = "/sdcard/mypackage";   // hard-coded, poor approach
        // BUG: DoNotHardCodeSDCard
        storageLocation = System.getenv("SECONDARY_STORAGE") + "/mypackage"; // preferred approach
    }

    public String showBug() {
        foo();
        return "/sdcard/mypackage"; // This is the value that is generated by the buggy code
    }
}

// Mutation Operator: Unreachable switch statement
class UnreachableSwitchStatement {
    void unreachableSwitchStatement() {
        boolean unreachableCondition = false;
        int value = getValue();
        switch(value) {
            case 1:
                System.out.println("Inside case 1");
                break;
            default:
                System.out.println("Inside default");
                break;
        }
        switch(unreachableCondition) {
            case 2:
                System.out.println("Inside case 2");
                break;
            default:
                System.out.println("Inside default");
                break;
        }
    }
    int getValue() {
        return 1;
    }
}