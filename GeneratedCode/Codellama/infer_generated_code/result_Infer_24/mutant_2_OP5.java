class InvariantHoist {
    @ThreadSafe
    public void invariantHoist(int size) {
        int x = 10;
        int y = 5;
        for (int i = 0; i < size; i++) {
            foo(x, y); // hoistable
        }

        // Unreachable switch statement
        switch (false) {
            case 1:
                System.out.println("Hello, World!");
                break;
            case 2:
                System.out.println("Goodbye, World!");
                break;
            default:
                break;
        }
    }

    @ThreadSafe
    @TrueOnNull
    public int foo(int x, int y) {
        return x + y;
    }

    public void showBug() {
        invariantHoist(5);
    }
}