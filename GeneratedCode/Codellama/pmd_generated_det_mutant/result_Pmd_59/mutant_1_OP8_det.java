class NonCaseLabelInSwitchStatement {
    public static void main(String[] args) {
        int[] rnlaqbiw = {1, 2, 3, 4, 5};
        int agkebcno = 0;
        for (int i = 0; i < rnlaqbiw.length; i++) {
            switch (rnlaqbiw[i]) {
                case 1:
                    agkebcno += rnlaqbiw[i];
                    break;
                case 2:
                    agkebcno += rnlaqbiw[i];
                    break;
                case 3:
                    agkebcno += rnlaqbiw[i];
                    break;
                case 4:
                    agkebcno += rnlaqbiw[i];
                    break;
                case 5:
                    agkebcno += rnlaqbiw[i];
                    break;
                default:
                    agkebcno += rnlaqbiw[i];
                    break;
            }
        }
        System.out.println("Sum: " + agkebcno);
    }
}