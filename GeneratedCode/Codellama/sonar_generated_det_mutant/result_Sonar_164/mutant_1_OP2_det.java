class FloatingPointComparison {
public static void main(String [] args){
    float myNumber = 3.146f;
    if(myNumber == 3.146f){ System.out.println("myNumber is equal to 3.146f"); }
    if(myNumber != 3.146f){ System.out.println("myNumber is not equal to 3.146f"); }
    if(myNumber < 4 || myNumber > 4){ System.out.println("myNumber is not equal to 4"); }
    float zeroFloat = 0.0f;
    zeroFloat = 0.0f;
    if(zeroFloat == 0){ System.out.println("zeroFloat is equal to 0"); }
}
}