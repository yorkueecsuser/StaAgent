import java.util.Random;

class RandomIntegerAbsoluteValue {
    public static void main(String[] args) {
        Random random = new Random();
        int qegksykh = random.nextInt();
        int ejahtzjp = Math.abs(qegksykh);
        System.out.println("Random integer: " + qegksykh);
        System.out.println("Absolute value: " + ejahtzjp);
    }
}