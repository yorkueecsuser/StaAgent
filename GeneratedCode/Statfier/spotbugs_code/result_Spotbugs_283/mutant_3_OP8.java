import edu.umd.cs.findbugs.annotations.NoWarning;
import java.util.Date;
import org.joda.time.DateTimeConstants;
import org.joda.time.Instant;
import org.joda.time.Interval;

class Ideas_2010_02_24 {

  @ExpectWarning("ICAST_INT_2_LONG_AS_INSTANT")
  public Date bad1(int x) {
    return new Date(x * 1000);
  }

  @ExpectWarning("ICAST_INT_2_LONG_AS_INSTANT")
  public Date bad2(int a) {
    return new Date(1000 * a);
  }

  @ExpectWarning("ICAST_INT_2_LONG_AS_INSTANT")
  public java.sql.Date bad3(int b) {
    return new java.sql.Date(1000 * b);
  }

  @ExpectWarning("ICAST_INT_2_LONG_AS_INSTANT")
  public Instant bad4(int c) {
    return new Instant(c * 1000);
  }

  @ExpectWarning("ICAST_INT_2_LONG_AS_INSTANT")
  public Date bad5(int d) {
    return new Date(d);
  }

  @ExpectWarning("ICAST_INT_2_LONG_AS_INSTANT")
  public java.sql.Date bad6(int e) {
    return new java.sql.Date(e);
  }

  @ExpectWarning("ICAST_INT_2_LONG_AS_INSTANT")
  public Instant bad7(int f) {
    return new Instant(f);
  }

  public Interval maybeOK(int g) {
    return new Interval(
        g * DateTimeConstants.MILLIS_PER_HOUR, (g + 1) * DateTimeConstants.MILLIS_PER_HOUR);
  }

  public Interval bad8(int h, int i) {
    return new Interval(h * 1000, i * 1000);
  }

  public static void main(String args[]) {
    long j = System.currentTimeMillis();
    System.out.println(Long.toHexString(j));
    System.out.println(Long.toHexString(j / 1000));
    System.out.println(Integer.MAX_VALUE - j / 1000);
    System.out.println(new Date(Integer.MIN_VALUE));
    System.out.println(new Date(0));
    System.out.println(new Date(Integer.MAX_VALUE));
    System.out.println(new Date(Integer.MAX_VALUE * 1000L));
  }

  /**
   * Checking FP NPE warnings generated by Eclipse to ensure we don't generate them
   *
   * <p>https://bugs.eclipse.org/bugs/show_bug.cgi?id=195638
   */
  @ExpectWarning(value = "NP_NULL_ON_SOME_PATH_EXCEPTION")
  @NoWarning(value = "NP_ALWAYS_NULL,NP_NULL_ON_SOME_PATH")
  public static void falsePositive() {
    String k = null;
    for (int l = 0; l < 2; l++) {
      try {
        k = new String("Test");
      } catch (Exception m) {
        m.printStackTrace();
      }
      k.charAt(l); // Error : "Null pointer access: The
      // variable str can only be null at
      // this location"
      k = null;
    }
  }

  @ExpectWarning(value = "NP_NULL_ON_SOME_PATH")
  public static void truePositive(boolean n) {
    String o = null;
    for (int p = 0; p < 2; p++) {
      if (n) o = new String("Test");

      o.charAt(p); // Error : "Null pointer access: The
      // variable str can only be null at
      // this location"
      o = null;
    }
  }
}